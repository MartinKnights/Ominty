"""Playlist rewriting: put an m3u into track order.

An ``.m3u`` has no track-number field — the order of the entries *is* the
playback order. Playlists generated by directory listing therefore play in
lexicographic order, which puts ``Track 10`` before ``Track 2``. This module
rewrites the entries in natural order (digits compared as numbers), keeping
each entry's ``#EXTINF`` / ``#EXTVLCOPT`` lines attached to it.

Only ``.m3u`` and ``.m3u8`` are supported. ``.pls`` is a different format
(indexed ``FileN=`` keys) and is deliberately refused rather than half-handled.
"""

from __future__ import annotations

import re
import shutil
import time
from pathlib import Path

SUPPORTED_SUFFIXES = (".m3u", ".m3u8")


class PlaylistError(ValueError):
    """A playlist that cannot be read or rewritten."""


def natural_key(text: str) -> list:
    """Sort key that compares digit runs as numbers ("Track 2" < "Track 10")."""
    return [
        int(part) if part.isdigit() else part.lower()
        for part in re.split(r"(\d+)", text)
    ]


def read_m3u(path: Path) -> tuple[list[str], list[tuple[list[str], str]]]:
    """Split an m3u into its header and (directives, path) entries."""
    header: list[str] = []
    entries: list[tuple[list[str], str]] = []
    pending: list[str] = []

    for raw in path.read_text(errors="replace").splitlines():
        line = raw.strip()
        if not line:
            continue
        if line.startswith("#"):
            if line.upper().startswith("#EXTM3U") and not header and not entries and not pending:
                header.append(line)
            else:
                pending.append(line)
            continue
        entries.append((pending, line))
        pending = []

    return header, entries


def render_m3u(header: list[str], entries: list[tuple[list[str], str]]) -> str:
    lines = list(header) or ["#EXTM3U"]
    for directives, path in entries:
        lines.extend(directives)
        lines.append(path)
    return "\n".join(lines) + "\n"


def sort_playlist(
    path: str | Path,
    *,
    in_place: bool = False,
    dry_run: bool = False,
) -> dict:
    """Return the playlist in natural order, optionally rewriting it.

    ``in_place`` writes the file and keeps a timestamped ``.bak-ominty-*``
    copy, but only when the order actually changes. ``dry_run`` reports what
    would happen without touching anything.
    """
    p = Path(path).expanduser()
    if not p.is_file():
        raise PlaylistError(f"no such playlist: {p}")
    if p.suffix.lower() == ".pls":
        raise PlaylistError(
            "'.pls' playlists are not supported — convert to .m3u, or reorder in the player"
        )
    if p.suffix.lower() not in SUPPORTED_SUFFIXES:
        raise PlaylistError(f"not an m3u playlist: {p.name}")

    header, entries = read_m3u(p)
    if not entries:
        raise PlaylistError(f"no entries in {p}")

    ordered = sorted(entries, key=lambda e: natural_key(Path(e[1]).name))
    changed = [e[1] for e in ordered] != [e[1] for e in entries]
    text = render_m3u(header, ordered)

    result = {
        "playlist": str(p),
        "entries": len(entries),
        "changed": changed,
        "written": False,
        "backup": None,
        "text": text,
    }

    if in_place and not dry_run and changed:
        backup = p.with_name(f"{p.name}.bak-ominty-{time.strftime('%Y%m%d-%H%M%S')}")
        shutil.copy2(p, backup)
        p.write_text(text)
        result["written"] = True
        result["backup"] = str(backup)

    return result
